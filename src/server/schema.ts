import { migrateAbbl } from "./abbl/schema";
import { pool, tx } from "./db";
import { migrateSupersets } from "./supersetMigrate";

export const SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS settings (
  id integer PRIMARY KEY CHECK (id = 1),
  display_name text NOT NULL,
  kcal_target integer NOT NULL,
  protein_target integer NOT NULL,
  carb_target integer NOT NULL,
  fat_target integer NOT NULL,
  weight_target numeric NOT NULL,
  ramp jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS exercises (
  id text PRIMARY KEY,
  name text NOT NULL,
  pattern_key text NOT NULL,
  pattern_label text NOT NULL,
  muscles text NOT NULL,
  is_cardio boolean NOT NULL DEFAULT false,
  measure text NOT NULL DEFAULT 'reps'
);

CREATE TABLE IF NOT EXISTS exercise_substitutes (
  exercise_id text NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
  substitute_id text NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
  sort_order integer NOT NULL,
  PRIMARY KEY (exercise_id, substitute_id)
);

CREATE TABLE IF NOT EXISTS program_days (
  id text PRIMARY KEY,
  name text NOT NULL,
  summary text NOT NULL,
  sort_order integer NOT NULL
);

CREATE TABLE IF NOT EXISTS program_exercises (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day_id text NOT NULL REFERENCES program_days(id) ON DELETE CASCADE,
  exercise_id text NOT NULL REFERENCES exercises(id),
  sort_order integer NOT NULL,
  sets integer NOT NULL,
  reps_label text NOT NULL,
  rep_count integer NOT NULL,
  measure text NOT NULL DEFAULT 'reps',
  per_side boolean NOT NULL DEFAULT false,
  notes text,
  is_cardio boolean NOT NULL DEFAULT false,
  cardio_min integer,
  superset_group text,
  superset_order integer
);

CREATE TABLE IF NOT EXISTS sessions (
  id uuid PRIMARY KEY,
  day_id text REFERENCES program_days(id),
  name text NOT NULL,
  started_at timestamptz NOT NULL,
  completed_at timestamptz,
  week_start date NOT NULL,
  sample boolean NOT NULL DEFAULT false,
  glucose_summary jsonb
);

CREATE TABLE IF NOT EXISTS session_exercises (
  id uuid PRIMARY KEY,
  session_id uuid NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
  program_exercise_id integer REFERENCES program_exercises(id) ON DELETE SET NULL,
  exercise_id text NOT NULL REFERENCES exercises(id),
  name text NOT NULL,
  sort_order integer NOT NULL,
  sets integer NOT NULL,
  reps_label text NOT NULL,
  rep_count integer NOT NULL,
  measure text NOT NULL DEFAULT 'reps',
  per_side boolean NOT NULL DEFAULT false,
  notes text,
  is_cardio boolean NOT NULL DEFAULT false,
  cardio_min integer,
  superset_group text,
  superset_order integer,
  skipped boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS sets (
  id uuid PRIMARY KEY,
  session_exercise_id uuid NOT NULL REFERENCES session_exercises(id) ON DELETE CASCADE,
  exercise_id text NOT NULL REFERENCES exercises(id),
  set_index integer NOT NULL,
  weight_lb numeric,
  reps numeric,
  duration_sec integer,
  note text,
  is_pr boolean NOT NULL DEFAULT false,
  pr_kind text,
  logged_at timestamptz,
  migrated boolean NOT NULL DEFAULT false,
  skipped boolean NOT NULL DEFAULT false,
  skip_source text
);

CREATE TABLE IF NOT EXISTS meals (
  id uuid PRIMARY KEY,
  logged_at timestamptz NOT NULL,
  name text NOT NULL,
  calories numeric NOT NULL,
  protein numeric NOT NULL,
  carbs numeric NOT NULL,
  fat numeric NOT NULL,
  note text,
  photo text,
  sample boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS favorites (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  calories numeric NOT NULL,
  protein numeric NOT NULL,
  carbs numeric NOT NULL,
  fat numeric NOT NULL,
  note text,
  last_used_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS weights (
  id uuid PRIMARY KEY,
  weighed_on date NOT NULL UNIQUE,
  weight_lb numeric NOT NULL,
  weighed_at timestamptz NOT NULL,
  sample boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS meals_logged_idx ON meals (logged_at);
CREATE INDEX IF NOT EXISTS sets_exercise_idx ON sets (exercise_id, logged_at);
CREATE INDEX IF NOT EXISTS sessions_week_idx ON sessions (week_start);
CREATE INDEX IF NOT EXISTS session_exercises_session_idx ON session_exercises (session_id);

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS glucose_summary jsonb;
ALTER TABLE meals ADD COLUMN IF NOT EXISTS glucose_summary jsonb;
ALTER TABLE meals ADD COLUMN IF NOT EXISTS nightscout_id text;
ALTER TABLE meals ADD COLUMN IF NOT EXISTS nightscout_pending boolean NOT NULL DEFAULT false;
ALTER TABLE program_exercises ADD COLUMN IF NOT EXISTS superset_group text;
ALTER TABLE program_exercises ADD COLUMN IF NOT EXISTS superset_order integer;
ALTER TABLE session_exercises ADD COLUMN IF NOT EXISTS superset_group text;
ALTER TABLE session_exercises ADD COLUMN IF NOT EXISTS superset_order integer;
ALTER TABLE sets ADD COLUMN IF NOT EXISTS migrated boolean NOT NULL DEFAULT false;
ALTER TABLE sets ADD COLUMN IF NOT EXISTS skipped boolean NOT NULL DEFAULT false;
ALTER TABLE sets ADD COLUMN IF NOT EXISTS skip_source text;
ALTER TABLE session_exercises ADD COLUMN IF NOT EXISTS skipped boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS nightscout_deletes (
  nightscout_id text PRIMARY KEY,
  queued_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE sessions ADD COLUMN IF NOT EXISTS source_kind text;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS source_client text;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS deleted_at timestamptz;
ALTER TABLE weights ADD COLUMN IF NOT EXISTS note text;
ALTER TABLE weights ADD COLUMN IF NOT EXISTS source_kind text;
ALTER TABLE weights ADD COLUMN IF NOT EXISTS source_client text;

CREATE TABLE IF NOT EXISTS steady_oauth_clients (
  id text PRIMARY KEY,
  name text NOT NULL,
  redirect_uris jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS steady_oauth_codes (
  code_hash text PRIMARY KEY,
  client_id text NOT NULL REFERENCES steady_oauth_clients(id),
  redirect_uri text NOT NULL,
  code_challenge text NOT NULL,
  expires_at timestamptz NOT NULL,
  used_at timestamptz
);

CREATE TABLE IF NOT EXISTS steady_oauth_connections (
  id uuid PRIMARY KEY,
  client_id text NOT NULL REFERENCES steady_oauth_clients(id),
  name text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);

CREATE TABLE IF NOT EXISTS steady_api_tokens (
  id uuid PRIMARY KEY,
  token_hash text NOT NULL UNIQUE,
  kind text NOT NULL,
  name text NOT NULL,
  client_id text,
  connection_id uuid,
  expires_at timestamptz,
  last_used_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);

CREATE TABLE IF NOT EXISTS steady_refresh_tokens (
  token_hash text PRIMARY KEY,
  client_id text NOT NULL,
  connection_id uuid NOT NULL,
  expires_at timestamptz NOT NULL,
  revoked_at timestamptz
);

CREATE TABLE IF NOT EXISTS steady_mcp_audit (
  id uuid PRIMARY KEY,
  action text NOT NULL,
  target_kind text NOT NULL,
  target_id uuid,
  client_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);
`;

export async function migrate(): Promise<void> {
  await pool.query(SCHEMA_SQL);
  await tx(async (client) => {
    await migrateSupersets(client);
    await migrateAbbl(client);
  });
}
